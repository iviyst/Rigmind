const on = (channel: string) => (cb: (v: any) => void) => {
  const h = (_: unknown, v: any) => cb(v);
  ipcRenderer.on(channel, h);
  return () => ipcRenderer.removeListener(channel, h);
};
const call = (channel: string) => (...args: any[]) => ipcRenderer.invoke(channel, ...args);

